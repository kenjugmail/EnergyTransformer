"""Generate text with a saved REWT checkpoint and its original tokenizer."""
from __future__ import annotations

import argparse
from dataclasses import replace
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
import torch
from rewt.data import file_sha256
from rewt.evaluate import model_output
from rewt.position_memory import load_learning_checkpoint
from rewt.model import JointEnergyLM, TransformerLM
from rewt.bpe import checkpoint_tokenizer
from rewt.words import WordTokenizer


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint',required=True,type=Path)
    source=parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--prompt')
    source.add_argument('--prompt-file',type=Path)
    parser.add_argument('--max-new',type=int,default=96)
    parser.add_argument('--temperature',type=float,default=.7)
    parser.add_argument('--seed',type=int,default=1003)
    parser.add_argument('--greedy',action='store_true')
    parser.add_argument('--stop-newline',action='store_true')
    parser.add_argument('--rounds',type=int)
    parser.add_argument('--cache-history',action='store_true',
        help='cache causal prefix encodings for energy checkpoints without changing learned weights')
    parser.add_argument('--packed-projections',action='store_true',help='pack conditioning affines and precompute GRU inputs')
    parser.add_argument('--refinement-backend',choices=('reference','krylov2','directional'))
    parser.add_argument('--solver',choices=('reference','krylov2','certified','preconditioned'),
        help='opt into an architecture solver, retaining compatible checkpoint weights')
    parser.add_argument('--structured-preconditioner',action='store_true',help='factor the latent Schur system for a preconditioned solver')
    parser.add_argument('--device',choices=('cpu','cuda'),default='cpu')
    parser.add_argument('--disable-tf32',action='store_true',help='use full float32 for CUDA matmuls and cuDNN convolutions')
    parser.add_argument('--ring-cache',action='store_true',help='fixed-size observation cache for the GRU core')
    parser.add_argument('--cuda-graph',action='store_true',help='capture the entire fixed-shape decode step')
    parser.add_argument('--triton-refinement',action='store_true',help='fused inference kernel for the preconditioned solver')
    parser.add_argument('--triton-tile',type=int,choices=(0,64,128,256),default=0)
    parser.add_argument('--compile-refinement',action='store_true',
        help='compile the krylov2 refinement region; first-call compilation can be slow')
    parser.add_argument('--decode-cache',action='store_true',
        help='keep observation projections and mode matrices across generated bytes')
    parser.add_argument('--json',action='store_true')
    args=parser.parse_args()
    if not 1<=args.max_new<=4096 or not 0<args.temperature<float('inf'):
        parser.error('max-new must be in 1..4096 and temperature must be positive and finite')
    if args.rounds is not None and args.rounds<0:
        parser.error('rounds must be nonnegative')
    raw=args.prompt_file.read_bytes() if args.prompt_file else args.prompt.encode('utf-8')
    if not raw:
        parser.error('prompt cannot be empty')
    torch.set_num_threads(1)
    if args.disable_tf32:
        torch.backends.cuda.matmul.allow_tf32=False
        torch.backends.cudnn.allow_tf32=False
    model,saved=load_learning_checkpoint(args.checkpoint)
    from rewt.architecture import ArchitectureConfig,ArchitectureEnergyLM
    if args.refinement_backend and (args.solver or isinstance(model,ArchitectureEnergyLM)):
        parser.error('architecture checkpoints use --solver; --refinement-backend selects a legacy-model backend')
    if args.solver:
        try:
            updated=ArchitectureEnergyLM(ArchitectureConfig(**dict(vars(model.config),solver=args.solver)))
            updated.load_state_dict(model.state_dict(),strict=True)
            model=updated
        except (ValueError,RuntimeError,TypeError) as error:parser.error(str(error))
    if args.structured_preconditioner:
        if not isinstance(model,ArchitectureEnergyLM) or model.config.solver!='preconditioned':
            parser.error('structured-preconditioner requires a preconditioned architecture model')
        updated=ArchitectureEnergyLM(replace(model.config,preconditioner_factorization='structured'))
        updated.load_state_dict(model.state_dict());model=updated
    if args.cache_history or args.refinement_backend or args.packed_projections:
        if not isinstance(model,JointEnergyLM):
            parser.error('energy execution options require an energy checkpoint')
        changes={}
        if args.cache_history: changes['cache_history']=True
        if args.packed_projections: changes.update(cache_history=True,packed_projections=True)
        if args.refinement_backend: changes['refinement_backend']=args.refinement_backend
        try: cached=type(model)(replace(model.config,**changes))
        except ValueError as error: parser.error(str(error))
        cached.load_state_dict(model.state_dict(),strict=True)
        model=cached
    if args.compile_refinement:
        if isinstance(model,ArchitectureEnergyLM):parser.error('use --cuda-graph for the architecture model decode path')
        if not isinstance(model,JointEnergyLM): parser.error('compile-refinement requires an energy checkpoint')
        try: model.compile_refinement()
        except ValueError as error: parser.error(str(error))
    if args.rounds is not None and (args.ring_cache or args.cuda_graph or args.triton_refinement):
        updated=type(model)(replace(model.config,rounds=args.rounds));updated.load_state_dict(model.state_dict());model=updated
    model.to(args.device).eval()
    if isinstance(model,ArchitectureEnergyLM):model.prepare_inference()
    session=None
    ring=args.ring_cache or args.cuda_graph or args.triton_refinement or bool(args.triton_tile)
    if ring:
        from rewt.ring_decode import RingDecodeSession
        try:session=RingDecodeSession(model,cuda_graph=args.cuda_graph,triton=args.triton_refinement,triton_tile=args.triton_tile)
        except ValueError as error:parser.error(str(error))
    elif args.decode_cache:
        if isinstance(model,ArchitectureEnergyLM):parser.error('use --ring-cache for GRU variants; scan variants use the model state directly')
        from rewt.decode import EnergyDecodeSession
        try: session=EnergyDecodeSession(model,rounds=args.rounds)
        except ValueError as error: parser.error(str(error))
    try:
        tokenizer=checkpoint_tokenizer(saved)
        word_mode=isinstance(tokenizer,WordTokenizer)
        if tokenizer and len(tokenizer.pieces)!=model.config.vocab_size:
            raise ValueError('checkpoint tokenizer size mismatch')
        encoded=tokenizer.encode(raw,bos=True) if word_mode else tokenizer.encode(raw) if tokenizer else raw
    except ValueError as error:parser.error(str(error))
    if isinstance(model,TransformerLM) and len(encoded)+args.max_new>model.config.context:
        parser.error(f'this Transformer checkpoint requires prompt + generation <= {model.config.context} tokens')
    generator=torch.Generator(device=args.device).manual_seed(args.seed)
    sample_generator=torch.Generator().manual_seed(args.seed+1000000)
    kwargs={} if args.rounds is None else dict(rounds=args.rounds)
    cost=dict(gradient_calls=0,energy_calls=0,attempts=0)
    generated=[]
    with torch.inference_mode():
        prompt_tokens=torch.tensor([list(encoded)],dtype=torch.long,device=args.device)
        output=(session.prefill(prompt_tokens) if session else
                model_output(model,prompt_tokens,generator,**kwargs))
        for step in range(args.max_new):
            for key in cost:cost[key]+=output.details['cost'].get(key,0)
            logits=output.logits[0,-1].clone()
            if word_mode:logits[[tokenizer.bos_id,tokenizer.unk_id]]=-torch.inf
            if args.greedy:
                token=int(logits.argmax())
            else:
                probability=(logits/args.temperature).softmax(-1)
                uniform=torch.rand((),generator=sample_generator)
                token=int((probability.cumsum(-1)<uniform).sum().clamp_max(model.config.vocab_size-1))
            generated.append(token)
            if word_mode and token==tokenizer.eos_id:break
            piece=tokenizer.pieces[token] if tokenizer else bytes([token])
            if (args.stop_newline and b'\n' in piece) or step+1==args.max_new:
                break
            next_tokens=torch.tensor([[token]],dtype=torch.long,device=args.device)
            if ring:
                from rewt.model import Output
                output=Output(session.step(next_tokens,validate_values=False),None,dict(cost={}))
            else:
                output=(session.step(next_tokens) if session else
                        model_output(model,next_tokens,generator,state=output.state,**kwargs))
    result=tokenizer.decode_continuation(generated,prefix=raw) if word_mode else tokenizer.decode(generated) if tokenizer else bytes(generated)
    if args.stop_newline and b'\n' in result:
        result=result.split(b'\n',1)[0]+b'\n'
    if args.json:
        print(json.dumps(dict(prompt=raw.decode('utf-8',errors='replace'),
            generation=result.decode('utf-8',errors='replace'),generation_hex=result.hex(),
            checkpoint=str(args.checkpoint.resolve()),checkpoint_sha256=file_sha256(args.checkpoint),
            generated_tokens=len(generated),generated_bytes=len(result),cost=None if ring else cost,
            cost_scope='ring decode counters are not instrumented' if ring else 'model counters')))
    else:
        sys.stdout.buffer.write(result)
        if not result.endswith(b'\n'):sys.stdout.buffer.write(b'\n')


if __name__=='__main__':main()
