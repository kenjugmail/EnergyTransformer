"""Sample native byte checkpoints on CPU with bounded prompt chunks.

Run ``python -m energy_real.sample --checkpoint PATH --prompt 'The '``.
Defaults to greedy decoding. Positive temperature enables seeded sampling.
These research checkpoints are byte predictors, not instruction-tuned assistants.
"""
from __future__ import annotations

import argparse
import math
import pickle
from pathlib import Path

import torch

from .model import Config, LM


def validate_options(prompt, tokens, temperature, top_k, seed, prefill_chunk):
    if not isinstance(prompt, bytes) or not prompt:
        raise ValueError('Prompt must contain at least one byte')
    if type(tokens) is not int or not 1 <= tokens <= 4096:
        raise ValueError('Output bytes must be between 1 and 4096')
    if not isinstance(temperature, (int, float)) or not math.isfinite(temperature) or temperature < 0:
        raise ValueError('Temperature must be finite and nonnegative (zero is greedy)')
    if type(top_k) is not int or not 0 <= top_k <= 256:
        raise ValueError('Top-k must be between 0 and 256 (zero keeps all bytes)')
    if type(seed) is not int or not 0 <= seed < 2**63:
        raise ValueError('Seed must be an integer between 0 and 2**63 - 1')
    if type(prefill_chunk) is not int or not 1 <= prefill_chunk <= 4096:
        raise ValueError('Prefill chunk must be between 1 and 4096 bytes')


@torch.inference_mode()
def sample_bytes(model: LM, prompt: bytes, *, tokens=128, temperature=0., top_k=0,
                 seed=0, prefill_chunk=256) -> bytes:
    """Return prompt + sampled bytes without mutating model weights or global RNG.

    Prompt chunks bound per-call activations and logits. Energy/local-attention
    state is bounded; full-attention checkpoints still retain their full KV cache.
    Fact readers are inactive here; use HybridSession for evidence-backed reads.
    """
    validate_options(prompt, tokens, temperature, top_k, seed, prefill_chunk)
    if model.config.vocab != 256:
        raise ValueError('Sampling requires a byte-vocabulary checkpoint')
    device = model.embedding.weight.device
    generator = torch.Generator(device=device).manual_seed(seed)
    state = None
    for lo in range(0, len(prompt), prefill_chunk):
        chunk = torch.tensor([list(prompt[lo:lo + prefill_chunk])], dtype=torch.long, device=device)
        output, state = model(chunk, state)
    raw = bytearray(prompt)
    for index in range(tokens):
        logits = output[:, -1].float()
        if not bool(torch.isfinite(logits).all()):
            raise FloatingPointError('Checkpoint produced nonfinite logits')
        if temperature == 0 or top_k == 1:
            token = logits.argmax(-1, keepdim=True)
        else:
            # Subtraction before scaling prevents overflow at tiny temperatures.
            logits = logits.double()
            logits = (logits - logits.max(-1, keepdim=True).values) / temperature
            if top_k:
                values, indices = logits.topk(top_k, dim=-1)
                sampled = torch.multinomial(values.softmax(-1), 1, generator=generator)
                token = indices.gather(-1, sampled)
            else:
                token = torch.multinomial(logits.softmax(-1), 1, generator=generator)
        raw.append(int(token.item()))
        if index + 1 < tokens:
            output, state = model(token, state)
    return bytes(raw)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--prompt', default='The ')
    parser.add_argument('--tokens', type=int, default=128, help='Number of new bytes, not text tokens')
    parser.add_argument('--temperature', type=float, default=0., help='Zero for greedy decoding')
    parser.add_argument('--top-k', type=int, default=0)
    parser.add_argument('--seed', type=int, default=0)
    parser.add_argument('--prefill-chunk', type=int, default=256)
    parser.add_argument('--output', type=Path, help='Save exact prompt and generated bytes to a new file')
    args = parser.parse_args(argv)
    prompt = args.prompt.encode('utf-8')
    try:
        validate_options(prompt, args.tokens, args.temperature, args.top_k, args.seed, args.prefill_chunk)
        if args.output is not None and args.output.exists():
            raise ValueError(f'Output already exists: {args.output}')
    except ValueError as error:
        parser.error(str(error))
    torch.set_num_threads(2)
    try:
        saved = torch.load(args.checkpoint, map_location='cpu', weights_only=True)
        if not isinstance(saved, dict) or not isinstance(saved.get('config'), dict) or not isinstance(saved.get('weights'), dict):
            raise ValueError('Expected a native checkpoint with config and weights dictionaries')
        model = LM(Config(**saved['config'])).eval()
        model.load_state_dict(saved['weights'], strict=True)
        raw = sample_bytes(model, prompt, tokens=args.tokens, temperature=args.temperature,
                           top_k=args.top_k, seed=args.seed, prefill_chunk=args.prefill_chunk)
        if args.output is not None:
            with args.output.open('xb') as file:
                file.write(raw)
    except (OSError, ValueError, KeyError, TypeError, RuntimeError, FloatingPointError,
            EOFError, pickle.UnpicklingError) as error:
        parser.error(str(error))
    print(raw.decode('utf-8', errors='replace'))


if __name__ == '__main__':
    main()
