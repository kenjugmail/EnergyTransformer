"""Replay fixed long-recall examples with all four frozen model controls.

This is a presentation demo using already published test cases, not a new test.
Only prompt bytes are passed to inference; expected answers enter scoring later.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import torch
from rewt.fast_decode import FastDecodeSession
from rewt.streaming import load_streaming
from rewt.tasks import Task, score_response


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


@torch.inference_mode()
def predict(model, prompt, backend):
    raw = prompt.encode('utf-8')
    session = FastDecodeSession(model, capacity=len(raw)+40, backend=backend)
    for start in range(0, len(raw), 128):
        session.consume(torch.tensor([list(raw[start:start+128])], device=model.embedding.weight.device))
    ids = session.generate(40)[0].cpu().tolist()
    # Match the study's first-newline stop rule; retain every generated ID too.
    stop = ids.index(10)+1 if 10 in ids else len(ids)
    return bytes(ids[:stop]).decode('latin1'), ids, session.allocated_state_bytes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--device', choices=['cpu', 'cuda'], default='cpu')
    parser.add_argument('--decoder', choices=['eager', 'compile', 'graph'], default='eager')
    parser.add_argument('--seed', type=int, choices=[26301, 26302, 26303], default=26301)
    args = parser.parse_args()
    if args.output.exists():
        parser.error('use a new output directory')
    if args.decoder == 'graph' and args.device != 'cuda':
        parser.error('graph requires CUDA')
    torch.set_num_threads(1)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    study = ROOT/'reports/rewt_streaming_20261026'
    source = study/'tasks_test_long.jsonl'
    tasks = [Task(**json.loads(line)) for line in source.read_text().splitlines()]
    selected = [next((i, task) for i, task in enumerate(tasks) if task.steps == depth)
                for depth in (32, 64, 128)]
    report = dict(selection='First saved test row at each distractor length; all four controls; seed fixed before this demo. Previously published test cases, not new held-out evidence.',
                  seed=args.seed, device=args.device, decoder=args.decoder,
                  task_source=str(source), task_source_sha256=sha(source), checkpoints={}, rows=[])
    models = ['transformer', 'window_transformer', 'hybrid', 'hybrid_energy']
    for name in models:
        checkpoint = ROOT/f'runs/rewt_streaming_20261026/tasks_{name}_{args.seed}/best.pt'
        model, _ = load_streaming(checkpoint)
        model.to(args.device).eval()
        report['checkpoints'][name] = dict(path=str(checkpoint), sha256=sha(checkpoint))
        for index, task in selected:
            response, ids, state_bytes = predict(model, task.prompt, args.decoder)
            score = score_response(task, response)
            historical = json.loads((study/f'tasks_{name}_{args.seed}_test.json').read_text())['test_long']['rows'][index]
            assert response == historical['response'], (name, index, response, historical['response'])
            report['rows'].append(dict(model=name, index=index, id=task.id, distractors=task.steps,
                                       prompt=task.prompt, token_ids=ids, state_bytes=state_bytes,
                                       matches_published_response=True, **score))
        del model
    lines = ['REWT — fixed long-memory demo', report['selection'], '',
             'K is the important fact; X entries are distractors. Responses are generated byte by byte.',
             'All outputs, including mistakes, are shown. These three examples are illustrative.', '']
    for index, task in selected:
        lines += [f'{task.steps} distractors | row {index} | {len(task.prompt.encode())} input bytes',
                  'Input: '+task.prompt.strip(), 'Expected: '+task.response.strip()]
        for row in report['rows']:
            if row['index'] == index:
                lines.append(f"  {row['model']:20s} {row['response'].strip()!r:24s} {'correct' if row['both_correct'] else 'incorrect'}")
        lines.append('')
    lines += ['Full published long-recall study: 72 prompts × 3 seeds per model.',
              'Full Transformer 14.35%; window Transformer 21.30%; hybrid 86.11%; hybrid + energy 77.31%.',
              'Accuracy was tested at 32–128 distractors (up to 520 prompt bytes).',
              'The separate 8K-prefix benchmark measures execution cost, not 8K retrieval accuracy.']
    args.output.mkdir(parents=True)
    (args.output/'results.json').write_text(json.dumps(report, indent=2)+'\n')
    (args.output/'transcript.txt').write_text('\n'.join(lines)+'\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
