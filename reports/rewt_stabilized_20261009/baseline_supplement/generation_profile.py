"""Measure actual autoregressive generation after training, in fresh processes."""
import argparse
import json
import os
from pathlib import Path
import statistics
import subprocess
import sys
import time

ROOT=Path(__file__).resolve().parent
REPO=ROOT.parents[2]
sys.path.insert(0,str(REPO))
LABELS=dict(transformer="Supplemental Transformer")


def run_case(arm,seed):
    import torch
    from rewt.data import file_sha256
    from rewt.evaluate import generate_batch
    from rewt.experiment import load_model
    from rewt.improve import with_policy
    torch.set_num_threads(1);torch.set_num_interop_threads(1)
    row=json.loads((ROOT/f'seed_{seed}'/f'{arm}.json').read_text())
    path=Path(row['training']['checkpoint'])
    initial=file_sha256(path)
    model,cp=load_model(path)
    policy=row['language_policy']
    if arm!='transformer':
        model=with_policy(model,cp['arm'],policy['rounds'],policy['halting_tolerance'])
    plan=json.loads((ROOT/'selected_protocol.json').read_text())
    prompts=[bytes.fromhex(p['prompt_hex']) for p in plan['text_prompts'][:10]]
    values=[]
    for batch in (1,10):
        chosen=prompts[:batch]
        generate_batch(model,chosen,max_new=96,sampling=True,seed=seed+1831)
        cpu,wall=[],[]
        for _ in range(3):
            c,w=time.process_time(),time.perf_counter()
            outputs=generate_batch(model,chosen,max_new=96,sampling=True,seed=seed+1831)
            cpu.append(time.process_time()-c);wall.append(time.perf_counter()-w)
            assert len(outputs)==batch and all(len(x)==96 for x in outputs)
        values.append(dict(batch_size=batch,prefix_bytes=32,generated_bytes_per_sample=96,
            includes_prefix_prefill=True,cpu_seconds=cpu,wall_seconds=wall,
            median_cpu_ms_per_generated_byte=1000*statistics.median(cpu)/(96*batch),
            median_wall_ms_per_generated_byte=1000*statistics.median(wall)/(96*batch)))
    assert file_sha256(path)==initial
    record=dict(arm=arm,seed=seed,checkpoint_sha256=initial,inference_policy=policy,
                device='cpu',torch_threads=1,measurements=values)
    out=ROOT/'generation_profiles';out.mkdir(exist_ok=True)
    (out/f'{arm}_{seed}.json').write_text(json.dumps(record,indent=2)+'\n')


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--arm',choices=tuple(LABELS));parser.add_argument('--seed',type=int)
    args=parser.parse_args()
    if args.arm:
        run_case(args.arm,args.seed);return
    assert (ROOT/'complete.json').exists(), 'Finish training and primary evaluation first'
    plan=json.loads((ROOT/'selected_protocol.json').read_text())
    records=[]
    env={**os.environ,'OMP_NUM_THREADS':'1','OPENBLAS_NUM_THREADS':'1','MKL_NUM_THREADS':'1'}
    for arm in LABELS:
        for seed in plan['settings']['seeds']:
            path=ROOT/'generation_profiles'/f'{arm}_{seed}.json'
            if not path.exists():
                subprocess.run([sys.executable,str(Path(__file__).resolve()),'--arm',arm,'--seed',str(seed)],
                               cwd=REPO,env=env,check=True)
            records.append(json.loads(path.read_text()))
    values={}
    for arm in LABELS:
        values[arm]={}
        for batch in (1,10):
            costs=[next(m['median_cpu_ms_per_generated_byte'] for m in r['measurements'] if m['batch_size']==batch)
                   for r in records if r['arm']==arm]
            values[arm][str(batch)]=dict(mean=statistics.mean(costs),std=statistics.stdev(costs),values=costs)
    report=['# Actual text-generation runtime', '',
        'Each model runs in a fresh CPU process with one Torch thread. The fixed first one or ten declared text prompts are used; every prompt has 32 bytes and is followed by 96 actually sampled bytes. One warm-up and three timed repetitions use each checkpoint\'s validation-selected inference policy. Times include prefix preparation and every autoregressive call, and are normalized by generated bytes. Checkpoint files remain unchanged.', '',
        'The baseline implementation recomputes its causal prefix on incremental calls; REWT retains its recurrent state and observed-history buffer. These timings describe the actual implementations, not optimal kernels or a GPU architecture comparison. Shared-host CPU timings have limited precision.', '',
        '| Variant | Single-sample CPU ms / generated byte | Ten-sample CPU ms / generated byte |',
        '|---|---:|---:|']
    for arm in LABELS:
        cells=[f"{values[arm][str(b)]['mean']:.3f} ± {values[arm][str(b)]['std']:.3f}" for b in (1,10)]
        report.append(f'| {LABELS[arm]} | '+' | '.join(cells)+' |')
    (ROOT/'generation_runtime.json').write_text(json.dumps(dict(records=records,aggregate=values),indent=2)+'\n')
    (ROOT/'GENERATION_RUNTIME.md').write_text('\n'.join(report)+'\n')
    print(json.dumps(values,indent=2))


if __name__=='__main__':main()
